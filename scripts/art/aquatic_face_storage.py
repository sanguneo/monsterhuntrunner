"""Lossless runtime Float32 packing shared by the original aquatic face author."""
import struct,base64,json
def write_packed_face(result,path):
 values=[];parts=[]
 for part in result:
  meta={'name':part['name']}
  for key in ['position','normal','uv','color']:
   field=part[key];meta[key]=[len(values),len(field)];values.extend(field)
  parts.append(meta)
 raw=struct.pack('<'+'f'*len(values),*values)
 payload={'data':base64.b64encode(raw).decode(),'parts':parts}
 path.write_text("// Generated by original author-sea-witch-face.py; exact Float32 bytes, no quantization.\nimport { decodeAuthoredMeshes } from './DecodedAuthoredMesh';\nexport const authoredSeaWitchFace=decodeAuthoredMeshes("+json.dumps(payload,separators=(',',':'))+" as const);\n")
