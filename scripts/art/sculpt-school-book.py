"""Authored haunted-book cover with real recessed eye apertures. Blender 4.3, no external assets.
Writes editable source scene and deterministic runtime geometry data; not a rendered preview.
"""
import bpy, json, sys, math, hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[2];out=root/'.art/school-book-sculpt';out.mkdir(parents=True,exist_ok=True)
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
bpy.ops.mesh.primitive_cube_add(size=1, location=(-.14,0,0));cover=bpy.context.object;cover.name='carved-haunted-leather-cover'
cover.dimensions=(.64,.83,.085);bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
bevel=cover.modifiers.new('tailored rounded cover edges','BEVEL');bevel.width=.014;bevel.segments=3
bpy.ops.object.modifier_apply(modifier=bevel.name)
for side in [-1,1]:
 cx=-.14+side*.095;cy=.095;angle=side*.2
 outline=[(-.078,.040),(.074,.052),(.054,-.033),(-.057,-.026)]
 xy=[(cx+x*math.cos(angle)-y*math.sin(angle),cy+x*math.sin(angle)+y*math.cos(angle)) for x,y in outline]
 verts=[(x,y,z) for z in [-.12,.12] for x,y in xy]
 faces=[(3,2,1,0),(4,5,6,7)]+[(i,(i+1)%4,(i+1)%4+4,i+4) for i in range(4)]
 # Outline is clockwise: reverse every face to make the Boolean cutter outward.
 faces=[tuple(reversed(f)) for f in faces]
 m=bpy.data.meshes.new('eye-aperture-cutter');m.from_pydata(verts,[],faces);m.update();cutter=bpy.data.objects.new('eye-aperture-cutter',m);bpy.context.collection.objects.link(cutter)
 bpy.context.view_layer.objects.active=cover
 cut=cover.modifiers.new('real recessed eye opening','BOOLEAN');cut.operation='DIFFERENCE';cut.solver='EXACT';cut.object=cutter
 bpy.ops.object.modifier_apply(modifier=cut.name);bpy.data.objects.remove(cutter,do_unlink=True)
# A narrow fractured mouth is cut into the leather, never a floating moustache plate.
xy=[(-.30,-.087),(-.245,-.077),(-.20,-.095),(-.155,-.081),(-.11,-.10),(-.055,-.085),(.01,-.102),(-.055,-.106),(-.11,-.117),(-.155,-.100),(-.20,-.113),(-.245,-.096)]
verts=[(x,y,z) for z in [-.12,.12] for x,y in xy];n=len(xy)
faces=[tuple(range(n-1,-1,-1)),tuple(range(n,2*n))]+[(i,(i+1)%n,(i+1)%n+n,i+n) for i in range(n)]
m=bpy.data.meshes.new('fractured-mouth-cutter');m.from_pydata(verts,[],faces);m.update();cutter=bpy.data.objects.new('fractured-mouth-cutter',m);bpy.context.collection.objects.link(cutter)
bpy.ops.object.select_all(action='DESELECT');cutter.select_set(True);bpy.context.view_layer.objects.active=cutter;bpy.ops.object.mode_set(mode='EDIT');bpy.ops.mesh.select_all(action='SELECT');bpy.ops.mesh.normals_make_consistent(inside=False);bpy.ops.object.mode_set(mode='OBJECT')
bpy.context.view_layer.objects.active=cover;cut=cover.modifiers.new('fractured inset mouth','BOOLEAN');cut.operation='DIFFERENCE';cut.solver='EXACT';cut.object=cutter;bpy.ops.object.modifier_apply(modifier=cut.name);bpy.data.objects.remove(cutter,do_unlink=True)
bevel=cover.modifiers.new('worn aperture rim','BEVEL');bevel.width=.004;bevel.segments=2;bevel.limit_method='ANGLE'
bpy.context.view_layer.objects.active=cover;bpy.ops.object.modifier_apply(modifier=bevel.name)
# Geometry is authored in runtime XY/-Z coordinates; no GLB coordinate conversion is needed here.
mesh=cover.data;mesh.calc_loop_triangles();p=[];n=[];uv=[]
for tri in mesh.loop_triangles:
 normal=tri.normal.normalized()
 for vi in tri.vertices:
  v=cover.matrix_world @ mesh.vertices[vi].co
  p.extend(round(x,7) for x in v);n.extend(round(x,7) for x in normal)
  uv.extend([round((v.x+.46)/.64,7),round((v.y+.415)/.83,7)])
assert len(p)==len(n) and len(uv)*3==len(p)*2
payload={'position':p,'normal':n,'uv':uv};encoded=json.dumps(payload,separators=(',',':'))
target=root/'src/visual/creatures/v2/schoolBookGeometry.ts'
target.write_text('// Generated by scripts/art/sculpt-school-book.py; editable source scene is preserved in Library.\nexport const schoolBookCoverData = '+encoded+';\n')
bpy.ops.wm.save_as_mainfile(filepath=str(out/'book-cover-authoring.blend'),compress=True)
(out/'manifest.json').write_text(json.dumps({'triangles':len(p)//9,'geometrySha256':hashlib.sha256(encoded.encode()).hexdigest(),'sourceScene':'book-cover-authoring.blend','script':'scripts/art/sculpt-school-book.py','runtimeGeometry':'src/visual/creatures/v2/schoolBookGeometry.ts'},indent=2))
print('AUTHORED_BOOK_COVER',len(p)//9)
